# Compact factual index of layout IDs and official iRacing SVG URLs. No SVGs are bundled.
param([string]$MetadataPath)
$ErrorActionPreference='Stop'
if (!$MetadataPath) {
    $MetadataPath=Join-Path $env:TEMP 'racemate-track-map-metadata.json'
    Invoke-WebRequest -UseBasicParsing 'https://raw.githubusercontent.com/meowmachine/racing-track-maps-vector/main/from-iracing/iracing-tracks-metadata.json' -OutFile $MetadataPath
}
$metadata=Get-Content -Raw -LiteralPath $MetadataPath | ConvertFrom-Json
$configs=@($metadata.tracks | ForEach-Object { $_.configurations } | Sort-Object track_id)
if (($configs | Group-Object track_id | Where-Object Count -gt 1).Count) { throw 'Duplicate track IDs' }
$lines=@(('// Generated by tools/UpdateTrackMapIndex.ps1. Metadata snapshot: '+([datetime]$metadata.generated_at).ToString('yyyy-MM-dd')),
    '// Source: meowmachine/racing-track-maps-vector/from-iracing/iracing-tracks-metadata.json',
    '// Only identifiers and official CDN paths; no third-party geometry or SVG assets.')
foreach ($config in $configs) {
    $prefix='https://members-assets.iracing.com'
    if (!$config.svg_folder_url.StartsWith($prefix+'/public/track-maps/') -or $config.svg_folder_url -notmatch '^https://members-assets\.iracing\.com/[a-zA-Z0-9_/-]+$') { throw 'Unexpected asset URL' }
    $slug=$config.track_dirpath.Replace('\','-')
    if ($slug -notmatch '^[a-zA-Z0-9_-]+$') { throw 'Unexpected track slug' }
    $lines+='    {'+$config.track_id+',"'+$slug+'","'+$config.svg_folder_url.Substring($prefix.Length)+'"},'
}
$destination=Join-Path $PSScriptRoot '../src/TrackMapSources.inc'
[IO.File]::WriteAllLines($destination,$lines,[Text.UTF8Encoding]::new($false))
Write-Output ('Indexed '+$configs.Count+' track configurations.')
